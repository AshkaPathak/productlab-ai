/*
 * ProductLab AI - product strategy report
 * Assembles the whole workflow into a Markdown document with numbered
 * IEEE-style references. Used by the web app and the command-line tool.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory(require('./evidence.js'), require('./decision.js'), require('./planning.js'));
  } else (root.PL = root.PL || {}).report = factory(root.PL.evidence, root.PL.decision, root.PL.planning);
})(typeof globalThis !== 'undefined' ? globalThis : this, function (E, D, P) {
  'use strict';

  const pct = (x) => (Number.isFinite(x) ? Math.round(x * 100) + '%' : '-');
  const f2 = (x) => (Number.isFinite(x) ? x.toFixed(2) : '-');
  const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n+/g, ' ');

  /** Map finding IDs to reference numbers [n] in order of first citation. */
  function citationNumberer(project) {
    const order = [];
    const refOf = new Map((project.findings || []).map((f) => [f.id, f.ref]));
    return {
      cite(ids) {
        const nums = [];
        (ids || []).forEach((id) => {
          const ref = refOf.get(id);
          if (!ref) return;
          let n = order.indexOf(ref);
          if (n < 0) { order.push(ref); n = order.length - 1; }
          if (!nums.includes(n + 1)) nums.push(n + 1);
        });
        nums.sort((a, b) => a - b);
        return nums.length ? ' [' + nums.join('], [') + ']' : '';
      },
      list() { return order; }
    };
  }

  function selectedConcept(project, ranked) {
    const id = project.selectedConcept || (ranked && ranked[0] && ranked[0].id);
    return (project.concepts || []).find((c) => c.id === id) || null;
  }

  function build(project, options) {
    const o = Object.assign({ includeAudit: true }, options || {});
    const idx = E.buildIndex(project);
    const cite = citationNumberer(project);
    const out = [];
    const line = (s) => out.push(s == null ? '' : s);

    line('# ' + (project.name || 'Product strategy'));
    line('');
    if (project.team && project.team.length) line('*Team: ' + project.team.join(', ') + '*  ');
    line('*Generated by ProductLab AI on ' + new Date().toISOString().slice(0, 10) + '*');
    line('');
    line('## 1. Problem');
    line(project.challenge || '');
    if (project.hmw) { line(''); line('**How might we** ' + project.hmw.replace(/^how might we\s*/i, '')); }
    line('');

    line('## 2. Evidence base');
    const kinds = {};
    (project.findings || []).forEach((f) => { kinds[f.kind || 'finding'] = (kinds[f.kind || 'finding'] || 0) + 1; });
    line((project.findings || []).length + ' evidence findings from ' + (project.references || []).length + ' sources (' +
      Object.keys(kinds).map((k) => kinds[k] + ' ' + k).join(', ') + ').');
    line('');
    (project.findings || []).filter((f) => f.kind === 'statistic').slice(0, 8).forEach((f) => line('- ' + f.text + cite.cite([f.id])));
    line('');

    line('## 3. Validated needs');
    line('| ID | Need | Severity | Evidence |');
    line('|---|---|---|---|');
    (project.needs || []).forEach((n) => line('| ' + n.id + ' | ' + esc(n.statement) + ' | ' + (n.severity || '-') + ' | ' + (cite.cite(n.evidence).trim() || 'none') + ' |'));
    line('');

    if ((project.personas || []).length) {
      line('## 4. Personas');
      project.personas.forEach((p) => {
        line('**' + p.name + '** - ' + (p.role || '') + (p.note ? ' (' + p.note + ')' : ''));
        (p.pains || []).forEach((pain) => line('- ' + pain.text + cite.cite(pain.evidence)));
        line('');
      });
    }

    line('## 5. Concept alternatives');
    (project.concepts || []).forEach((c) => {
      line('### ' + c.name + (c.tagline ? ' - ' + c.tagline : ''));
      if (c.description) line(c.description);
      (c.claims || []).forEach((cl) => line('- ' + cl.text + cite.cite(cl.evidence)));
      line('');
    });

    const crit = project.criteria || [];
    const ranked = crit.length && (project.concepts || []).length ? D.wdm(project.concepts, crit, project.ratings || {}) : [];
    if (ranked.length) {
      const w = D.normalizeWeights(crit);
      line('## 6. Weighted decision matrix');
      line('Total score = sum of (weight x rating), ratings on a 1-5 scale.');
      line('');
      line('| Criterion (weight) | ' + ranked.map((r) => esc(r.name)).join(' | ') + ' |');
      line('|---|' + ranked.map(() => '---').join('|') + '|');
      crit.forEach((c, i) => line('| ' + esc(c.name) + ' (' + Math.round(w[i] * 100) + '%) | ' + ranked.map((r) => r.breakdown[i].rating).join(' | ') + ' |'));
      line('| **Weighted score** | ' + ranked.map((r) => '**' + f2(r.total) + '**').join(' | ') + ' |');
      line('| Rank | ' + ranked.map((r) => r.rank).join(' | ') + ' |');
      line('');
      const sens = D.sensitivity(project.concepts, crit, project.ratings || {});
      const mc = D.monteCarlo(project.concepts, crit, project.ratings || {}, { runs: 2000, spread: 0.3, seed: 42 });
      line('**Sensitivity.** ' + sens.map((s) => s.flip
        ? s.name + ': winner changes to ' + s.flip.newWinnerName + ' if its weight moves to ' + pct(s.flip.at) + ' (' + (s.flip.delta > 0 ? '+' : '') + Math.round(s.flip.delta * 100) + ' pts)'
        : s.name + ': no single-weight change alters the winner').join('; ') + '.');
      line('');
      line('**Robustness.** With every weight randomly perturbed by up to +/-30% (2,000 runs), ' +
        mc.map((m) => m.name + ' wins ' + pct(m.winRate)).join(', ') + '.');
      line('');
    }

    const sel = selectedConcept(project, ranked);
    if ((project.competitors || []).length) {
      line('## 7. Competitive landscape');
      line('| Competitor | Category | Strengths | Gaps |');
      line('|---|---|---|---|');
      project.competitors.forEach((c) => line('| ' + esc(c.name) + ' | ' + esc(c.category) + ' | ' + esc(c.strengths) + ' | ' + esc(c.gaps) + cite.cite(c.evidence) + ' |'));
      line('');
    }

    if (sel) {
      line('## 8. Selected concept: ' + sel.name);
      line(sel.description || '');
      line('');
    }

    if ((project.features || []).length) {
      const pr = P.prioritize(project, idx);
      line('## 9. Feature prioritisation (evidence-adjusted RICE)');
      line('RICE = Reach x Impact x Confidence / Effort; confidence is scaled by evidence strength (0.5 + 0.5 x evidence score).');
      line('');
      line('| # | Feature | MoSCoW | Reach % | Impact | Conf. % | Effort (pw) | Evidence | RICE | Adjusted |');
      line('|---|---|---|---|---|---|---|---|---|---|');
      pr.forEach((r) => {
        const f = r.feature;
        line('| ' + r.rank + ' | ' + esc(f.name) + cite.cite(f.evidence) + ' | ' + (f.moscow || r.suggestedMoscow) + ' | ' + f.reach + ' | ' + f.impact + ' | ' + f.confidence + ' | ' + f.effort + ' | ' + pct(r.evidence) + ' | ' + f2(r.raw) + ' | ' + f2(r.adjusted) + ' |');
      });
      line('');
      const s = P.schedule(project, { priority: pr.map((r) => r.feature.id) });
      line('## 10. MVP roadmap');
      line('Team of ' + s.settings.teamSize + ', ' + Math.round(s.settings.focus * 100) + '% focus, ' + s.settings.sprintWeeks + '-week sprints, ' + Math.round(s.settings.buffer * 100) + '% risk buffer.');
      line('');
      s.phases.forEach((ph) => {
        if (!ph.tasks.length) return;
        line('**' + ph.name + '** - ' + ph.tasks.length + ' features, ' + f2(ph.effort) + ' person-weeks, complete by week ' + Math.ceil(ph.weeks));
        ph.tasks.forEach((t) => line('- ' + t.name + ' (weeks ' + t.start.toFixed(1) + '-' + t.end.toFixed(1) + ', sprints ' + t.sprintStart + '-' + t.sprintEnd + ')'));
        line('');
      });
      if (s.cyclic.length) line('> Dependency cycle detected between: ' + s.cyclic.join(', '));
    }

    if (project.constraints) {
      line('## 11. Technology stack');
      P.recommendStack(project.constraints).forEach((r) => line('- **' + r.layer + ':** ' + r.choice + ' - ' + r.why.join('; ') + (r.alternatives.length ? ' (alternatives: ' + r.alternatives.join(', ') + ')' : '')));
      line('');
    }

    if (project.bmc) {
      line('## 12. Business Model Canvas');
      const labels = { customerSegments: 'Customer segments', valuePropositions: 'Value propositions', channels: 'Channels', customerRelationships: 'Customer relationships', revenueStreams: 'Revenue streams', keyResources: 'Key resources', keyActivities: 'Key activities', keyPartners: 'Key partners', costStructure: 'Cost structure' };
      Object.keys(labels).forEach((k) => { if (project.bmc[k]) line('- **' + labels[k] + ':** ' + esc(project.bmc[k])); });
      line('');
    }

    if ((project.risks || []).length) {
      line('## 13. Risks (inverse thinking)');
      line('| Failure mode | Likelihood | Impact | Mitigation |');
      line('|---|---|---|---|');
      project.risks.slice().sort((a, b) => b.likelihood * b.impact - a.likelihood * a.impact)
        .forEach((r) => line('| ' + esc(r.failure) + cite.cite(r.evidence) + ' | ' + r.likelihood + ' | ' + r.impact + ' | ' + esc(r.mitigation) + ' |'));
      line('');
    }

    if (o.includeAudit) {
      const a = E.audit(project, idx);
      const s = a.summary;
      line('## 14. Traceability audit');
      line('Every claim in this report was checked against the evidence it cites (TF-IDF similarity; supported >= ' + idx.opts.strong + ', partial >= ' + idx.opts.weak + ').');
      line('');
      line('- Claims checked: ' + s.total);
      line('- Supported: ' + s.supported + ', partially supported: ' + s.partial + ', not supported by cited source: ' + s.unsupported + ', cites missing evidence: ' + s.invalid + ', uncited: ' + s.uncited);
      line('- **Traceability index: ' + pct(s.traceability) + '**; evidence coverage: ' + s.evidenceUsed + '/' + s.evidenceTotal + ' findings used');
      line('');
    }

    line('## References');
    const refs = new Map((project.references || []).map((r) => [r.id, r]));
    cite.list().forEach((id, i) => { const r = refs.get(id); if (r) line('[' + (i + 1) + '] ' + E.formatIEEE(r)); });
    line('');
    return out.join('\n');
  }

  return { build, citationNumberer };
});
